std::string_view Ukrainian(std::string_view ru) {
    const auto& table = Table();
    if (auto it = table.find(ru); it != table.end()) return it->second;
    // A text without a Ukrainian entry stays Russian (tools/i18n_check.py should have caught it).
    static std::mutex mutex;
    static std::set<std::string, std::less<>> reported;
    std::lock_guard lock(mutex);
    if (reported.insert(std::string(ru)).second) log::Warn("No Ukrainian text for \"{}\"", ru);
    return ru;
}

